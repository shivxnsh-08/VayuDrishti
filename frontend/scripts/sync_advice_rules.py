"""Copy the backend's advice rules (forecast-service/advice/rules.yaml) into the frontend as JSON.

The rules are the single source of truth; the frontend never edits its copy by hand. Re-run after
changing rules.yaml:   python frontend/scripts/sync_advice_rules.py   (needs PyYAML)
"""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
src = ROOT / "forecast-service" / "advice" / "rules.yaml"
dst = ROOT / "frontend" / "src" / "lib" / "advice-rules.json"

rules = yaml.safe_load(src.read_text(encoding="utf-8"))
out = {
    "_source": "forecast-service/advice/rules.yaml (generated by frontend/scripts/sync_advice_rules.py; do not edit)",
    **rules,
}
dst.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print(f"wrote {dst.relative_to(ROOT)} ({len(rules['rules'])} rules, {len(rules['templates'])} templates)")
